SELECT MEMBER_ID,CALENDAR_YEAR_MONTH,MEMBER_LIFECYCLE_STATUS,CASE WHEN MEMBER_LIFECYCLE_STATUS = 'lapsed' 
		THEN LAG(R-1) OVER(PARTITION BY MEMBER_ID ORDER BY MEMBER_ID,CALENDAR_YEAR_MONTH,A) END AS R1 FROM
(
	SELECT MEMBER_ID,CALENDAR_YEAR_MONTH,MEMBER_LIFECYCLE_STATUS,ROW_NUMBER() OVER(PARTITION BY MEMBER_ID,A ORDER BY MEMBER_ID,CALENDAR_YEAR_MONTH,A) AS R
	FROM
	(
		SELECT MEMBER_ID,CALENDAR_YEAR_MONTH,MEMBER_LIFECYCLE_STATUS,
		SUM(CASE WHEN MEMBER_LIFECYCLE_STATUS = 'lapsed' THEN 1 ELSE 0 END) 
		OVER(PARTITION BY MEMBER_ID ORDER BY MEMBER_ID,CALENDAR_YEAR_MONTH) AS A
		FROM lapsed_count 
	)TBL
)TBL1 
ORDER BY MEMBER_ID
