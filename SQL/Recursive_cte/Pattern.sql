
--PATTERNS USING CTE
-- *  *  *  *  * 
-- *  *  *  * 
-- *  *  * 
-- *  * 
-- * 

DECLARE @N INT = 5

;WITH CTE
AS
(
	SELECT REPLICATE(' * ',@N) M,@N N
	UNION ALL
	SELECT REPLICATE(' * ',N-1) M,N-1 N FROM CTE WHERE N > 0
)
SELECT M FROM CTE

--IS THE PATREN WHICH WILL BE PRINTED IN ROW FORMAT AS WE HAVE USED SELECT STATEMENT INSTEAD OF PRINT CLAUSE
--TO ACHIVE THE SAME IN NORMAL FORMAT

DECLARE @N INT = 5

WHILE (@N > 0)
BEGIN
	PRINT REPLICATE(' * ',@N)

	SET @N = @N-1
END
