
CREATE TABLE EMP 
(
	ID INT,
	EMPNAME VARCHAR(120),
	MGRNAME INT
)

INSERT INTO EMP VALUES(1,'emp1',2),(2,'emp2',NULL),(3,'emp3',1),(4,'emp4',1),(5,'emp5',3)

--GET THE SUBORDINATE EMPLOYEE HIRARCHY (GET THE EMPLOYEE CHAIN OF THE CORRESPONDING EMPID)
--ID NAME   MGRNAME
--1	emp1	NULL
--3	emp3	emp1
--4	emp4	emp1
--5	emp5	emp3
;WITH CTE 
AS
(
	SELECT ID,EMPNAME,MGRNAME
	FROM EMP 
	WHERE ID = 1
	UNION ALL
	SELECT EMP.ID,EMP.EMPNAME,EMP.MGRNAME FROM CTE ,EMP
	WHERE CTE.ID = EMP.MGRNAME
)
SELECT C.ID,C.EMPNAME,M.EMPNAME AS MGRNAME 
FROM CTE C LEFT OUTER JOIN CTE M
ON C.MGRNAME = M.ID

--GET THE SUPPER ORDINATE EMPLOYEE HIRARCHY (GET THE PRIOR EMPLOYEE CHAIN OF THE CORRESPONDING EMPID)
--ID	EMPNAME	BOSSNAME
--5	emp5	emp3
--3	emp3	emp1
--1	emp1	emp2
--2	emp2	NULL
;WITH CTE 
AS
(
	SELECT ID,EMPNAME,MGRNAME
	FROM EMP 
	WHERE ID = 5
	UNION ALL
	SELECT EMP.ID,EMP.EMPNAME,EMP.MGRNAME FROM CTE ,EMP
	WHERE CTE.MGRNAME = EMP.ID
)
SELECT C.ID,C.EMPNAME,M.EMPNAME AS BOSSNAME 
FROM CTE C LEFT OUTER JOIN CTE M
ON C.MGRNAME = M.ID

--THE CODE DIFFERENCE BETWEEN BOTH OF THEN IS LIKE 
--IN SUBORDINATE EMPLOYEE HIRARCHY WE WILL CHECK THE ID/EMPID OF THE ANCHOR CLAUSE EQUAL TO MANAGERID OF THE EMP TABLE
--THIS MEANS WE WANT THE EMPLOYEE RECORD OF THE CURRENT MANAGER RECORD
--IN SUPERORDINATE EMPLOYEE HIRARCHY WE WILL CHECK THE MANAGERID OF THE ANCHOR CLAUSE EQUAL TO ID/EMPID OF THE EMP TABLE
--THIS MEANS WE WANT THE MANAGER RECORD OF THE CURRENT EMPLOYEE RECORD
